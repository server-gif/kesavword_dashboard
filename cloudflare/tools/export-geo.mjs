// Convert the DB-IP country-lite CSV (already downloaded in ../data/geo) into D1 `geo` rows.
// Run from the cloudflare/ folder:
//
//   node tools/export-geo.mjs
//
// Writes sql/geo.sql (batched multi-row INSERTs). Import with:
//   npx wrangler d1 execute dashboard-data --remote --file ./sql/geo.sql
//
// Geo is OPTIONAL: without it the Overview just shows "Unknown" for countries. IPv6 rows are
// skipped (the logs are almost all IPv4), matching the local lib/geo.js behaviour.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const FILE = path.resolve(here, '..', '..', 'data', 'geo', 'dbip-country-lite.csv.gz');
const OUT = path.resolve(here, '..', 'sql');
fs.mkdirSync(OUT, { recursive: true });

if (!fs.existsSync(FILE)) {
  console.error('Missing data/geo/dbip-country-lite.csv.gz — start the local dashboard once so it downloads, then re-run.');
  process.exit(1);
}

const ipv4ToInt = (ip) => {
  const p = ip.split('.');
  if (p.length !== 4) return -1;
  const n = p.map(Number);
  if (n.some((x) => !(x >= 0 && x <= 255))) return -1;
  return n[0] * 16777216 + n[1] * 65536 + n[2] * 256 + n[3];
};

const text = zlib.gunzipSync(fs.readFileSync(FILE)).toString('utf8');
const rows = [];
for (const line of text.split('\n')) {
  if (!line || line.includes(':')) continue; // skip IPv6
  const [a, b, cc] = line.trim().split(',');
  const s = ipv4ToInt(a);
  const e = ipv4ToInt(b);
  if (s < 0 || e < 0 || !/^[A-Z]{2}$/.test(cc || '')) continue;
  rows.push(`(${s},${e},'${cc}')`);
}

const BATCH = 500;
const out = ['-- generated by tools/export-geo.mjs', 'DELETE FROM geo;'];
for (let i = 0; i < rows.length; i += BATCH) {
  out.push(`INSERT INTO geo (start, "end", cc) VALUES ${rows.slice(i, i + BATCH).join(',')};`);
}
fs.writeFileSync(path.join(OUT, 'geo.sql'), out.join('\n'));
console.log(`Wrote sql/geo.sql — ${rows.length} IPv4 ranges.`);
console.log('Import: npx wrangler d1 execute dashboard-data --remote --file ./sql/geo.sql');
