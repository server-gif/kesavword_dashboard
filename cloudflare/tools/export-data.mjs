// Convert the local ./data files into D1 SQL so your existing accounts, activity history and
// "ignored" notes carry over to the Worker. Run from the cloudflare/ folder:
//
//   node tools/export-data.mjs
//
// It writes sql/data.sql. Import it with:
//   npx wrangler d1 execute dashboard-data --local  --file ./sql/data.sql   (test)
//   npx wrangler d1 execute dashboard-data --remote --file ./sql/data.sql   (production)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.resolve(here, '..', '..', 'data');
const OUT = path.resolve(here, '..', 'sql');
fs.mkdirSync(OUT, { recursive: true });

const readJson = (p, fb) => { try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return fb; } };
const esc = (s) => `'${String(s).replace(/'/g, "''")}'`;
const escNull = (s) => (s === undefined || s === null ? 'NULL' : esc(s));

const out = ['-- generated by tools/export-data.mjs — safe to re-run on a fresh D1 only', ''];

// users
const users = readJson(path.join(DATA, 'users.json'), []);
for (const u of users) {
  out.push(`INSERT INTO users (id, data, updated_at) VALUES (${esc(u.id)}, ${esc(JSON.stringify(u))}, ${Date.now()});`);
}
out.push('');

// ignored + trash as settings blobs
const ignored = readJson(path.join(DATA, 'ignored.json'), {});
out.push(`INSERT OR REPLACE INTO settings (key, value) VALUES ('ignored', ${esc(JSON.stringify(ignored))});`);
const trash = readJson(path.join(DATA, 'trash.json'), []);
out.push(`INSERT OR REPLACE INTO settings (key, value) VALUES ('trash', ${esc(JSON.stringify(trash))});`);
out.push('');

// activity + diffs
const logFile = path.join(DATA, 'activity.jsonl');
if (fs.existsSync(logFile)) {
  for (const line of fs.readFileSync(logFile, 'utf8').split('\n')) {
    if (!line.trim()) continue;
    let e;
    try { e = JSON.parse(line); } catch { continue; }
    out.push(
      `INSERT OR IGNORE INTO activity (id, ts, user, name, action, path, to_path, detail, size, has_diff) VALUES (`
      + `${esc(e.id)}, ${e.ts}, ${esc(e.user)}, ${esc(e.name)}, ${esc(e.action)}, `
      + `${escNull(e.path)}, ${escNull(e.to)}, ${escNull(e.detail)}, ${escNull(e.size)}, ${e.hasDiff ? 1 : 0});`
    );
    const gz = path.join(DATA, 'history', `${e.id}.json.gz`);
    if (fs.existsSync(gz)) {
      // store raw gzip bytes as an SQLite BLOB literal so the Worker's gunzip reads it directly
      const hex = fs.readFileSync(gz).toString('hex');
      out.push(`INSERT OR IGNORE INTO diffs (id, gz) VALUES (${esc(e.id)}, X'${hex}');`);
    }
  }
}

fs.writeFileSync(path.join(OUT, 'data.sql'), out.join('\n'));
console.log(`Wrote sql/data.sql — ${users.length} users, activity from ${path.basename(logFile)}`);
console.log('Next: npx wrangler d1 execute dashboard-data --local --file ./sql/data.sql');
